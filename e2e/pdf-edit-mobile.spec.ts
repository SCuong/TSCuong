import AxeBuilder from '@axe-core/playwright';

async function upload(page: Page, route: string, file: FilePayload) {
  await page.goto('/read/tools/' + route);
  await page.locator('.pdf-toolkit input[type=file]').first().setInputFiles(file);
}
async function formFixture() {
  const doc = await PDFDocument.create(); const page = doc.addPage([595, 842]); const form = doc.getForm();
  const name = form.createTextField('Full name'); name.addToPage(page, { x: 50, y: 700, width: 300, height: 30 });
  const accept = form.createCheckBox('I agree'); accept.addToPage(page, { x: 50, y: 650, width: 20, height: 20 });
  const city = form.createDropdown('City'); city.addOptions(['Hanoi', 'Bangkok']); city.select('Hanoi'); city.addToPage(page, { x: 50, y: 600, width: 200, height: 30 });
  const choice = form.createRadioGroup('Delivery'); choice.addOptionToPage('Email', page, { x: 50, y: 550, width: 20, height: 20 }); choice.addOptionToPage('Post', page, { x: 100, y: 550, width: 20, height: 20 });
  const fixed = form.createTextField('Reference'); fixed.setText('READ ONLY'); fixed.enableReadOnly(); fixed.addToPage(page, { x: 50, y: 500, width: 200, height: 30 });
  return { name: 'Application.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await doc.save()) };
}
test('form fields export real editable values and restore a local draft', async ({ page }) => {
  const fixture = await formFixture();
  await upload(page, 'pdf-forms', fixture);
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Alex Nguyen');
  await page.getByRole('checkbox', { name: 'I agree' }).check();
  await page.getByLabel('City', { exact: true }).selectOption('Bangkok');
  await page.getByRole('radio', { name: 'Delivery: Post' }).check();
  await expect(page.getByRole('textbox', { name: /Reference/ })).toBeDisabled();
  await page.getByRole('button', { name: 'Export filled copy' }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download', exact: true }).click();
  const output = await readFile((await (await download).path())!);
  const form = (await PDFDocument.load(output)).getForm();
  expect(form.getTextField('Full name').getText()).toBe('Alex Nguyen');
  expect(form.getCheckBox('I agree').isChecked()).toBe(true);
  expect(form.getDropdown('City').getSelected()).toEqual(['Bangkok']);
  expect(form.getRadioGroup('Delivery').getSelected()).toBe('Post');
  expect(form.getTextField('Reference').getText()).toBe('READ ONLY');
  await page.screenshot({ path: 'test-results/pdf-forms-mobile.png', fullPage: true });
  await page.reload(); await page.locator('.pdf-toolkit input[type=file]').first().setInputFiles(fixture);
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveValue('Alex Nguyen');
  await expect(page.getByRole('checkbox', { name: 'I agree' })).toBeChecked();
  const results = await new AxeBuilder({ page }).analyze();
  expect(results.violations.filter((v) => v.impact === 'critical' || v.impact === 'serious')).toEqual([]);
});
test('real text selection, touch drawing, notes and signatures persist and export', async ({ page, context }) => {
  const fixture = await makePdf('Notes.pdf', 2, 'Meeting notes');
  await upload(page, 'pdf-annotate', fixture);
  const cdp = await context.newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
  await expect(page.locator('.textLayer')).toContainText('Meeting notes');
  await page.locator('.textLayer span').first().evaluate((element) => { const range = document.createRange(); range.selectNodeContents(element); const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range); });
  await page.getByRole('button', { name: 'Highlight', exact: true }).click();
  await page.getByLabel('Color', { exact: true }).evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, '#22c55e'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.getByRole('button', { name: 'Highlight selection', exact: true }).click();
  await expect(page.locator('.pdf-edit-overlay rect').first()).toHaveAttribute('fill', '#22c55e');
  await expect(page.getByLabel('Annotations on this page')).toContainText('Highlight');
  await page.getByRole('button', { name: 'Draw', exact: true }).click();
  const bounds = (await page.getByRole('img', { name: 'Page drawing area' }).boundingBox())!;
  await page.getByRole('img', { name: 'Page drawing area' }).scrollIntoViewIfNeeded();
  const actual = (await page.getByRole('img', { name: 'Page drawing area' }).boundingBox())!;
  const x = actual.x + 30, y = actual.y + 100;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 70, y: y + 20 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(page.getByLabel('Annotations on this page')).toContainText('Draw');
  await page.getByRole('button', { name: 'Signature', exact: true }).click();
  await page.getByRole('img', { name: 'Page drawing area' }).scrollIntoViewIfNeeded();
  const sig = (await page.getByRole('img', { name: 'Page drawing area' }).boundingBox())!;
  await page.mouse.move(sig.x + 40, sig.y + 160); await page.mouse.down(); await page.mouse.move(sig.x + 140, sig.y + 180, { steps: 8 }); await page.mouse.up();
  await page.getByRole('button', { name: 'Text note', exact: true }).click();
  await page.getByRole('textbox', { name: 'Text note' }).fill('Ghi chú tiếng Việt');
  await page.getByRole('button', { name: 'Place note in center' }).click();
  await expect(page.getByLabel('Annotations on this page')).toContainText('Ghi chú tiếng Việt');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  const fitWidth = (await page.locator('.pdf-edit-paper').boundingBox())!.width;
  await page.getByLabel('Annotation zoom', { exact: true }).selectOption('2');
  expect((await page.locator('.pdf-edit-paper').boundingBox())!.width).toBeCloseTo(fitWidth * 2, 0);
  await page.getByLabel('Annotation zoom', { exact: true }).selectOption('1');
  await expect(page.getByLabel('Annotations on this page')).not.toContainText('Ghi chú tiếng Việt');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.getByRole('button', { name: 'Edit annotation 4', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox', { name: 'Text note' }).fill('Ghi chú tiếng Việt — đã sửa');
  await page.getByRole('button', { name: 'Save note', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  const noteBounds = (await page.locator('.pdf-edit-overlay foreignObject').boundingBox())!;
  await page.getByRole('button', { name: 'Export annotated copy' }).click();
  await expect(page.getByRole('button', { name: 'Read exported PDF' })).toBeVisible();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download', exact: true }).click();
  const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
  const bytes = await readFile((await (await download).path())!);
  const exported = await PDFDocument.load(bytes);
  const images = exported.context.enumerateIndirectObjects().map(([, object]) => object).filter((object): object is PDFRawStream => object instanceof PDFRawStream && object.dict.get(PDFName.of('Subtype')) === PDFName.of('Image'));
  expect(images.length).toBeGreaterThan(0);
  for (const image of images) {
    const width = image.dict.lookup(PDFName.of('Width'), PDFNumber).asNumber();
    const height = image.dict.lookup(PDFName.of('Height'), PDFNumber).asNumber();
    expect(height / width).toBeCloseTo(noteBounds.height / noteBounds.width, 2);
  }
  const task = pdfjs.getDocument({ data: new Uint8Array(bytes), verbosity: 0 }); const doc = await task.promise;
  const annotations = await (await doc.getPage(1)).getAnnotations();
  expect(annotations.some((annotation) => annotation.contentsObj?.str === 'Ghi chú tiếng Việt')).toBe(true);
  await task.destroy();
  expect(bounds.width).toBeGreaterThan(200);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0);
  await page.reload(); await page.locator('.pdf-toolkit input[type=file]').first().setInputFiles(fixture);
  await expect(page.getByLabel('Annotations on this page')).toContainText('Ghi chú tiếng Việt');
  await page.getByRole('button', { name: 'Select text / scroll' }).click();
  await page.locator('.pdf-edit-paper').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/pdf-annotations-mobile.png' });
  const results = await new AxeBuilder({ page }).analyze();
  expect(results.violations.filter((v) => v.impact === 'critical' || v.impact === 'serious')).toEqual([]);
});

test('clearing editing drafts keeps the source PDF and reader bookmarks', async ({ page }) => {
  const source = await makePdf('Keep original.pdf', 2);
  await upload(page, 'pdf-annotate', source);
  await page.getByRole('button', { name: 'Text note', exact: true }).click();
  await page.getByRole('textbox', { name: 'Text note' }).fill('Local draft'); await page.getByRole('button', { name: 'Place note in center' }).click();
  await page.getByRole('button', { name: 'Bookmark this page' }).click();
  await expect(page.getByText('Edits saved on this device. Export a copy to keep your markup in the PDF.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Read source PDF' }).click(); await expect(page.locator('.reader-draft-overlay')).toContainText('Local draft');
  await page.getByRole('button', { name: 'Back to library' }).click(); await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(page.getByText('1 document editing drafts saved', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear annotation and form drafts' }).click(); await page.getByRole('button', { name: 'Clear drafts', exact: true }).click();
  await expect(page.getByText('0 document editing drafts saved', { exact: true })).toBeVisible(); await page.getByRole('link', { name: 'Library', exact: true }).click();
  await page.locator('.reader-document-open').filter({ hasText: 'Keep original.pdf' }).click();
  await expect(page.getByRole('heading', { name: 'Keep original.pdf', exact: true })).toBeVisible();
  await expect(page.locator('.reader-draft-overlay')).toHaveCount(0);
  await page.getByRole('button', { name: 'Pages', exact: true }).click(); await page.getByRole('button', { name: 'Bookmarks', exact: true }).click();
  await expect(page.locator('.reader-bookmarks')).toContainText('Page 1');
});
