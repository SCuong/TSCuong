export interface HeaderFilter {
  query: string;
  direction: HeaderDirection | 'all';
  category: HeaderCategory | 'all';
}

export function filterHeaders(list: HeaderInfo[], { query, direction, category }: HeaderFilter): HeaderInfo[] {
  const q = query.trim().toLowerCase();
  const words = q ? q.split(/\s+/) : [];
  const scored: Array<[HeaderInfo, number]> = [];
  for (const h of list) {
    if (direction !== 'all' && h.direction !== direction && h.direction !== 'both') continue;
    if (category !== 'all' && h.category !== category) continue;
    if (!words.length) {
      scored.push([h, 0]);
      continue;
    }
    const name = h.name.toLowerCase();
    const hay = `${name} ${h.category} ${h.description} ${h.examples.join(' ')} ${h.spec} ${h.status}`.toLowerCase();
    if (!words.every((w) => hay.includes(w))) continue;
    const score = name === q ? 3 : name.startsWith(q) ? 2 : name.includes(q) ? 1 : 0;
    scored.push([h, score]);
  }
  return scored.sort((a, b) => b[1] - a[1] || a[0].name.localeCompare(b[0].name, 'en', { sensitivity: 'base' })).map(([h]) => h);
}
